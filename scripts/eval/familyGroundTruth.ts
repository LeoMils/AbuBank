/*
 * scripts/eval/familyGroundTruth.ts — Part 3 ORACLE for the FAMILY domain.
 * ════════════════════════════════════════════════════════════════════════════
 * A test that asserts against the same dataset it reads is circular (the Gilad defect:
 * no test knew null was wrong, so an 81-year-old corrected the assistant). This emits the
 * INDEPENDENT oracle the owner fills ONCE: every entity's derived relation to Martita and
 * every gap the code cannot derive. From then on FAMILY_GROUND_TRUTH.md is the oracle the
 * never-null test checks against.
 *
 *   npx vite-node scripts/eval/familyGroundTruth.ts
 * Writes docs/eval/FAMILY_GROUND_TRUTH.md + docs/eval/family-ground-truth.json.
 * No secrets, no phone numbers (peopleModel carries none). Deterministic — no model, no cost.
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadPeople } from '../../src/services/people/peopleModel'
import { whoIs, relationshipBetween } from '../../src/services/people/peopleLookup'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')

function main() {
  const people = loadPeople()
  const rows = people.map((p) => {
    const w = whoIs(p.hebrewName, people)
    const rel = w.status === 'ok' ? w.relationToMartita : null
    return { id: p.id, name: p.hebrewName, gender: p.gender, deceased: !!p.deceased, role: p.role ?? null, relationToMartita: rel }
  })

  // GAP = a family entity (not Martita herself) whose relation to Martita cannot be derived
  // AND has no role to fall back on. These are the cells the owner fills once.
  const gaps = rows.filter((r) => r.id !== 'martita' && !r.relationToMartita)

  // Unresolvable ordered pairs (not_found only — 'unrelated' is legitimate for a friend).
  const ids = people.map((p) => p.id)
  const nameById = new Map(people.map((p) => [p.id, p.hebrewName]))
  let pairOk = 0, pairUnrelated = 0, pairNotFound = 0
  const notFoundPairs: string[] = []
  for (const x of ids) for (const y of ids) {
    if (x === y) continue
    const r = relationshipBetween(nameById.get(x)!, nameById.get(y)!, people)
    if (r.status === 'ok') pairOk++
    else if (r.status === 'unrelated') pairUnrelated++
    else { pairNotFound++; if (notFoundPairs.length < 40) notFoundPairs.push(`${nameById.get(x)}→${nameById.get(y)}`) }
  }

  const L: string[] = []
  L.push('# FAMILY_GROUND_TRUTH — the oracle for the family domain')
  L.push('')
  L.push('GENERATED by `scripts/eval/familyGroundTruth.ts` from the people model. It is the')
  L.push('independent oracle: the never-null test asserts against the "relation to Martita"')
  L.push('column, and every GAP below is a cell the OWNER fills ONCE (bounded data entry, not QA).')
  L.push('Do not hand-edit the derived column; fix the data (knowledge/family_data.json) or the resolver.')
  L.push('')
  L.push(`People: ${rows.length} · Gaps (no derivable relation AND no role): ${gaps.length}`)
  L.push(`Ordered pairs: ${pairOk} resolved · ${pairUnrelated} unrelated (friends, legitimate) · ${pairNotFound} not_found`)
  L.push('')
  L.push('## Every entity → relation to Martita')
  L.push('| id | name | gender | relation to Martita | role | deceased |')
  L.push('|---|---|---|---|---|---|')
  for (const r of rows) {
    L.push(`| ${r.id} | ${r.name} | ${r.gender} | ${r.relationToMartita ?? '**— GAP —**'} | ${r.role ?? ''} | ${r.deceased ? 'yes' : ''} |`)
  }
  L.push('')
  if (gaps.length) {
    L.push('## GAPS — owner fills these once')
    for (const g of gaps) L.push(`- **${g.name}** (${g.id}) — no relation to Martita derivable and no role. Add the missing edge in knowledge/family_data.json.`)
  } else {
    L.push('## GAPS — none. Every entity has a derivable relation to Martita or a stated role.')
  }
  L.push('')
  if (notFoundPairs.length) {
    L.push('## Sample not_found ordered pairs (first 40) — expected only for genuinely disconnected people')
    L.push(notFoundPairs.join(' · '))
  }
  writeFileSync(join(ROOT, 'docs/eval/FAMILY_GROUND_TRUTH.md'), L.join('\n') + '\n')
  writeFileSync(join(ROOT, 'docs/eval/family-ground-truth.json'), JSON.stringify({ people: rows, gaps, pairs: { ok: pairOk, unrelated: pairUnrelated, notFound: pairNotFound } }, null, 2))
  console.log(`people=${rows.length} gaps=${gaps.length} pairs ok=${pairOk} unrelated=${pairUnrelated} notFound=${pairNotFound}`)
  console.log('GAPS:', gaps.map((g) => g.name).join(', ') || '(none)')
}
main()
